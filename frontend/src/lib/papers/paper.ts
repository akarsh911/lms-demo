export function patternAdoptions(
  paper: PaperRow,
  marks: PatternFigure,
  minutes: PatternFigure,
): string[] {
  const lines: string[] = [];
  if (marks.state === 'derived' && marks.value !== paper.total_marks) {
    lines.push(
      typeof paper.total_marks === 'number'
        ? `It is stored out of ${trimNumber(paper.total_marks)} and this pattern marks it out of ${trimNumber(marks.value)}.`
        : `This pattern marks it out of ${trimNumber(marks.value)}.`,
    );
  }
  if (minutes.state === 'derived' && minutes.value !== paper.duration_minutes) {
    lines.push(
      typeof paper.duration_minutes === 'number'
        ? `It is stored at ${durationLabel(paper.duration_minutes)} and this pattern allows ${durationLabel(minutes.value)}.`
        : `This pattern allows ${durationLabel(minutes.value)}, where the paper states no time at all.`,
    );
  }
  return lines;
}
