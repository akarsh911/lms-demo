  'questions after it keep the numbers they already had. The freed position can ' +
  'be used again straight away.';

export function gapsIn(questions: readonly PaperQuestionRow[]): number[] {
  const taken = new Set(
    questions
      .map((question) => question.position)
      .filter((position): position is number => typeof position === 'number'),
  );
  if (taken.size === 0) return [];
  const highest = Math.max(...taken);
  const missing: number[] = [];
  for (let position = 1; position <= highest; position += 1) {
    if (!taken.has(position)) missing.push(position);
  }
  return missing;
}

export function nextFreePosition(questions: readonly PaperQuestionRow[]): number {
  const gaps = gapsIn(questions);
  if (gaps.length > 0) return gaps[0]!;
  const taken = questions
    .map((question) => question.position)
    .filter((position): position is number => typeof position === 'number');
  return taken.length === 0 ? 1 : Math.max(...taken) + 1;
}

export type PatternFigure =
  | { state: 'own' }
  | { state: 'pending' }
  | { state: 'unreadable' }
  | { state: 'derived'; value: number };

export function figureFromPattern(
  chosen: boolean,
  pending: boolean,
  value: number | undefined,
): PatternFigure {
  if (!chosen) return { state: 'own' };
  if (pending) return { state: 'pending' };
  return typeof value === 'number' ? { state: 'derived', value } : { state: 'unreadable' };
}

