import { writeFileSync } from 'node:fs';

process.env.NEXT_PUBLIC_DEV_BYPASS_USER = process.env.DEV_BYPASS_USER?.trim() || 'teacher';

const planner = await import('../../../src/fixtures/lesson-planner.ts');
const plans = await import('../../../src/fixtures/lesson-plans.ts');
const calendar = await import('../../../src/fixtures/lesson-calendar.ts');
const term = await import('../../../src/fixtures/lesson-term.ts');
const guides = await import('../../../src/fixtures/data/lesson-planner.ts');
const termData = await import('../../../src/fixtures/data/lesson-term.ts');
const { config } = await import('../../../src/config.ts');
const identity = await import('../../../src/fixtures/identity.ts');
const people = await import('../../../src/fixtures/data/people.ts');

const PERSONAS = ['admin', 'teacher', 'student', 'parent', 'dev'];

const OUT = new URL('./seed.json', import.meta.url);
const GOLDEN = new URL('../tests/golden.json', import.meta.url);

const context = planner.context();
const offerings = context.offerings;

const curricula = Object.fromEntries(
  [...new Set(offerings.flatMap((o) => (o.curriculum_id ? [o.curriculum_id] : [])))].map((id) => {
    const grade = offerings.find((o) => o.curriculum_id === id)?.grade ?? 0;
    return [id, { grade, chapters: planner.outline(id).chapters }];
  }),
);

const grades = Object.fromEntries(
  [...new Set(offerings.map((o) => o.grade))].map((grade) => [
    String(grade),
    { days: calendar.termDays(grade), exam_windows: calendar.examWindows(grade) },
  ]),
);

const syllabusKey = (o) => o.curriculum_id ?? `grade:${o.grade}`;

const syllabi = {};
for (const offering of offerings) {
  const key = syllabusKey(offering);
  if (syllabi[key]) continue;
  const { exams, units, chapters } = term.termContext(offering.offering_id);
  syllabi[key] = { exams, units, chapters };
}

const week = plans.week(context.today, null);

const calendarDays = Object.fromEntries(
  [...planner.calendarOf.entries()].map(([date, day]) => [date, { open: Boolean(day.forenoon_open), name: day.name ?? null }]),
);

plans.listPlans();
const seedPlans = globalThis.__emergeLessonPlans.map((plan) => ({
  id: plan.id,
  offering_id: plan.offering_id,
  curriculum_node_id: plan.curriculum_node_id,
  period_count: plan.periods.length,
  title: plan.title,
  start: plan.created_at.slice(0, 10),
  created_at: plan.created_at,
  author_id: plan.author_id,
  author_name: plan.author_name,
  reflections: plan.periods.map((period) => period.taught?.reflection ?? null),
  slots: plan.periods.map((period) => (period.slot ? `${period.slot.date}|${period.slot.period_id}` : null)),
}));

const authorName = (personId) => people.STAFF.find((row) => row.person_id === personId)?.edges?.person?.display_name ?? 'You';

const personas = {};
for (const user of PERSONAS) {
  config.devUser = user;
  const { roles, person } = identity.identity();
  personas[user] = {
    person_id: person?.id ?? null,
    author_name: authorName(person?.id),
    is_teacher: Boolean(roles?.is_teacher),
    is_staff: Boolean(roles?.is_staff),
    offering_ids: roles?.is_teacher ? (roles.subject_offering_ids ?? []) : [],
  };
}
config.devUser = process.env.NEXT_PUBLIC_DEV_BYPASS_USER;

const seedAuthor = personas[config.devUser];
const mineFlags = offerings.filter((row) => row.mine).map((row) => row.offering_id).sort();
if (JSON.stringify(mineFlags) !== JSON.stringify([...new Set(seedAuthor.offering_ids)].filter((id) => offerings.some((row) => row.offering_id === id)).sort())) {
  throw new Error('persona offering ids disagree with the fixture mine flags');
}

const seed = {
  source: 'generated by seed/export_seed.mjs from src/fixtures; do not edit by hand',
  default_user: 'teacher',
  seed_author_id: seedAuthor.person_id,
  personas,
  offerings,
  curricula,
  guides: guides.CHAPTER_GUIDES,
  periods: week.periods,
  calendar: calendarDays,
  terms: termData.PLANNER_TERMS,
  grades,
  syllabi,
  seed_plans: seedPlans,
};

writeFileSync(OUT, `${JSON.stringify(seed, null, 1)}\n`);

const stripIds = (value) => {
  if (Array.isArray(value)) return value.map(stripIds);
  if (value && typeof value === 'object') {
    return Object.fromEntries(Object.entries(value).filter(([key]) => key !== 'id').map(([key, inner]) => [key, stripIds(inner)]));
  }
  return value;
};

const target = offerings.find((o) => o.offering_id === seedPlans[0]?.offering_id) ?? offerings[0];
const goldenCases = target?.curriculum_id
  ? curricula[target.curriculum_id]?.chapters.slice(0, 5).map((chapter, i) => ({
      offering_id: target.offering_id,
      curriculum_node_id: chapter.id,
      topic_ids: chapter.topics.slice(0, i % 3).map((topic) => topic.id),
      period_count: 1 + ((i * 3) % 8),
      objectives: i === 1 ? ['Custom objective'] : [],
    })) ?? []
  : [];

const science = offerings.find((o) => o.grade === 10 && o.subject_code === 'SCI' && o.curriculum_id);
const scienceChapter = (title) => (science ? curricula[science.curriculum_id]?.chapters.find((chapter) => chapter.title === title) : undefined);
const life = scienceChapter('Life Processes');
const acids = scienceChapter('Acids, Bases and Salts');
if (!life || !acids?.topics[1]) throw new Error('focus golden cases need Life Processes and a two-topic Acids, Bases and Salts');
goldenCases.push(
  { offering_id: science.offering_id, curriculum_node_id: life.id, topic_ids: [], period_count: 3, objectives: [], focus_topics: ['Respiration'] },
  {
    offering_id: science.offering_id,
    curriculum_node_id: acids.id,
    topic_ids: [acids.topics[1].id],
    period_count: 4,
    objectives: [],
    focus_topics: [acids.topics[1].title, 'Neutralisation', acids.topics[0].title],
  },
);

const generated = goldenCases.map((request) => ({ request, response: stripIds(planner.generate(request)) }));

const blockCases = generated.flatMap(({ request, response }) => {
  return ['warm_up', 'explanation', 'activity', 'check', 'homework'].flatMap((kind, k) =>
    [0, 1, 2].map((variant) => {
      const period = response.periods[(k + variant) % response.periods.length];
      return {
        offering_id: request.offering_id,
        curriculum_node_id: request.curriculum_node_id,
        kind,
        focus: variant === 2 ? 'A focus nobody authored' : (period?.focus ?? ''),
        period_sequence: period?.sequence ?? 1,
        period_count: request.period_count,
        minutes: variant === 1 ? 0 : 9,
        variant,
      };
    }),
  );
});

const blocks = blockCases.map((request) => ({ request, response: stripIds(planner.regenerateBlock(request)) }));

const termPlans = [...new Set(seedPlans.map((plan) => plan.offering_id))].map((offeringId) => ({ offering_id: offeringId, response: term.termPlan(offeringId) }));

writeFileSync(GOLDEN, `${JSON.stringify({ generate: generated, blocks, term_plans: termPlans }, null, 1)}\n`);

console.log(`seed.json: ${offerings.length} offerings, ${Object.keys(curricula).length} curricula, ${Object.keys(grades).length} grades, ${Object.keys(syllabi).length} syllabi, ${seedPlans.length} seed plans, personas ${JSON.stringify(Object.fromEntries(Object.entries(personas).map(([user, row]) => [user, [row.author_name, row.is_teacher, row.is_staff, row.offering_ids.length]])))}`);
console.log(`golden.json: ${generated.length} generate cases, ${blocks.length} block cases, ${termPlans.length} term plan defaults`);
